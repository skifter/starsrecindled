    /** @return array<string, mixed>|null */
    private function productionDefinition(string $item, array $state, int $playerId, string $modelId = '', string $productionKind = '', string $sourceModelId = ''): ?array
    {
        $legacy = [
            'Scout Wing' => 'current_scout',
            'Defense Grid' => 'defense_grid_mk1',
            'Orbital Factory' => 'orbital_factory_mk1',
            'Deep Space Array' => 'deep_space_array_mk1',
        ];
        $requested = $modelId !== '' ? $modelId : ($legacy[$item] ?? $item);
        if ($requested === 'current_scout') {
            $design = TechnologyModelCatalog::currentDesign($state, $playerId);
            return [
                'kind' => 'ship', 'modelId' => (string) $design['id'], 'name' => (string) $design['name'],
                'version' => (int) ($design['generation'] ?? 1), 'cost' => max(1, (int) ($design['industryCost'] ?? 300)), 'design' => $design,
            ];
        }
        $design = TechnologyModelCatalog::resolveDesign($state, $playerId, $requested);
        if ($design !== null) {
            return [
                'kind' => 'ship', 'modelId' => (string) $design['id'], 'name' => (string) $design['name'],
                'version' => (int) ($design['generation'] ?? 1), 'cost' => max(1, (int) ($design['industryCost'] ?? 300)), 'design' => $design,
            ];
        }
        $model = TechnologyModelCatalog::model($requested);
        if ($model === null || ($model['category'] ?? null) !== 'installation') {
            return null;
        }
        $catalog = TechnologyModelCatalog::publicForPlayer($state, $playerId);
        $allowed = false;
        foreach ($catalog['installations'] as $candidate) {
            if (($candidate['id'] ?? null) === $requested && ($candidate['unlocked'] ?? false) === true) {
                $allowed = true;
                break;
            }
        }
        if (!$allowed) {
            return null;
        }
        if ($productionKind === 'upgrade') {
            $upgrade = TechnologyModelCatalog::installationUpgradeDefinition($state, $playerId, $sourceModelId, $requested);
            if ($upgrade === null) {
                return null;
            }
            $source = TechnologyModelCatalog::model($sourceModelId);
            return [
                'kind' => 'upgrade', 'modelId' => (string) $upgrade['id'], 'name' => sprintf('Upgrade to %s', (string) $upgrade['name']),
                'version' => (int) $upgrade['version'], 'cost' => max(1, (int) ($upgrade['upgradeCost'] ?? 0)), 'turns' => max(1, (int) ($upgrade['upgradeTurns'] ?? 1)),
                'sourceModelId' => $sourceModelId, 'sourceName' => (string) ($source['name'] ?? $sourceModelId), 'sourceVersion' => (int) ($source['version'] ?? 1), 'model' => $upgrade,
            ];
        }
        return [
            'kind' => 'installation', 'modelId' => (string) $model['id'], 'name' => (string) $model['name'],
            'version' => (int) $model['version'], 'cost' => max(1, (int) ($model['stats']['industryCost'] ?? 0)), 'model' => $model,
        ];
    }

    /**
     * Consume one component-backed colony ship when possible. Legacy starting
     * fleets keep the old single-use fleet-level module behavior.
     *
     * @param array<string, mixed> $fleet
     * @return array{fleet:array<string,mixed>|null,designName:string|null,shipConsumed:bool}
     */
    private function consumeColonyCapacity(array $fleet): array
    {
        $composition = is_array($fleet['composition'] ?? null) ? array_values($fleet['composition']) : [];
        foreach ($composition as $index => $entry) {
            if (!is_array($entry)) {
                continue;
            }
            $stats = is_array($entry['stats'] ?? null) ? $entry['stats'] : [];
            $perShip = max(0, (int) ($stats['colonizationCapacity'] ?? 0));
            $quantity = max(0, (int) ($entry['quantity'] ?? 0));
            if ($perShip < 1 || $quantity < 1) {
                continue;
            }

            $designName = is_string($entry['designName'] ?? null) ? $entry['designName'] : null;
            --$quantity;
            if ($quantity <= 0) {
                array_splice($composition, $index, 1);
            } else {
                $composition[$index]['quantity'] = $quantity;
            }

            $fleet['composition'] = array_values($composition);
            $fleet['ships'] = max(0, (int) ($fleet['ships'] ?? 0) - 1);
            $fleet['colonizationCapacity'] = max(0, $this->colonyCapacity($fleet) - $perShip);
            if ((int) $fleet['ships'] <= 0) {
                return ['fleet' => null, 'designName' => $designName, 'shipConsumed' => true];
            }

            return ['fleet' => $fleet, 'designName' => $designName, 'shipConsumed' => true];
        }

        $legacyCapacity = max(
            0,
            (int) ($fleet['legacyColonizationCapacity'] ?? $this->colonyCapacity($fleet)),
        );
        $fleet['legacyColonizationCapacity'] = max(0, $legacyCapacity - 1);
        $fleet['colonizationCapacity'] = max(0, $this->colonyCapacity($fleet) - 1);
        return ['fleet' => $fleet, 'designName' => null, 'shipConsumed' => false];
    }

    /** @param array<string, mixed> $fleet */
    private function colonyCapacity(array $fleet): int
    {
        if (isset($fleet['colonizationCapacity']) && is_numeric($fleet['colonizationCapacity'])) {
            return max(0, (int) $fleet['colonizationCapacity']);
        }

        if (isset($fleet['legacyColonizationCapacity']) && is_numeric($fleet['legacyColonizationCapacity'])) {
            return max(0, (int) $fleet['legacyColonizationCapacity']);
        }

        // Backwards compatibility for pre-dev6 starting test games.
        return ($fleet['role'] ?? null) === 'Exploration fleet' ? 1 : 0;
    }

    /** @param list<mixed> $routes */
    private function systemDistance(array $routes, string $a, string $b, int $maxDistance): ?int
    {
        if ($a === '' || $b === '') {
            return null;
        }
        if ($a === $b) {
            return 0;
        }

        $adjacency = [];
        foreach ($routes as $route) {
            if (!is_array($route)) {
                continue;
            }
            $from = is_string($route['from'] ?? null) ? $route['from'] : '';
            $to = is_string($route['to'] ?? null) ? $route['to'] : '';
            if ($from === '' || $to === '') {
                continue;
            }
            $adjacency[$from][] = $to;
            $adjacency[$to][] = $from;
        }

        $visited = [$a => true];
        $frontier = [$a];
        for ($distance = 1; $distance <= max(1, $maxDistance); ++$distance) {
            $next = [];
            foreach ($frontier as $systemId) {
                foreach ($adjacency[$systemId] ?? [] as $neighbourId) {
                    if (isset($visited[$neighbourId])) {
                        continue;
                    }
                    if ($neighbourId === $b) {
                        return $distance;
                    }
                    $visited[$neighbourId] = true;
                    $next[] = $neighbourId;
                }
            }
            if ($next === []) {
                break;
            }
            $frontier = $next;
        }

        return null;
    }
